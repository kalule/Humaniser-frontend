// ── Types ─────────────────────────────────────────────────────────────────────

type DetectorState = 'idle' | 'analysing' | 'complete'
type VerdictType = 'likely-ai' | 'mixed' | 'likely-human'
type ConfidenceType = 'high' | 'medium' | 'low'

interface SentenceResult {
  id: string
  text: string
  aiProbability: number
}

interface DetectorUIResult {
  overallAiPct: number
  verdict: VerdictType
  confidence: ConfidenceType
  sentences: SentenceResult[]
  wordCount: number
  analysedAt: string
}

// ── Helpers ───────────────────────────────────────────────────────────────────

const SAMPLE_TEXT = `Artificial intelligence has transformed the way we approach problem-solving across industries. The utilisation of machine learning algorithms enables organisations to process vast datasets with unprecedented efficiency. Furthermore, the integration of natural language processing capabilities has facilitated more sophisticated human-computer interaction paradigms. It is important to note that these technological advancements present both opportunities and challenges for contemporary society. The systematic implementation of AI-driven solutions requires careful consideration of ethical implications and potential societal impacts.`

function adaptResponse(r: DetectResponse): DetectorUIResult {
  const verdict: VerdictType =
    r.aiScore >= 70 ? 'likely-ai' : r.aiScore >= 40 ? 'mixed' : 'likely-human'
  const confidence: ConfidenceType =
    r.isLowConfidence ? 'low' : r.wordCount >= 200 ? 'high' : r.wordCount >= 100 ? 'medium' : 'low'
  return {
    overallAiPct: r.aiScore,
    verdict,
    confidence,
    sentences: r.sentenceScores.map((s, i) => ({
      id: `s${i}`,
      text: s.sentence,
      aiProbability: s.aiProbability,
    })),
    wordCount: r.wordCount,
    analysedAt: new Date().toISOString(),
  }
}

function generateReportText(result: DetectorUIResult): string {
  return `AI Detection Report — ${new Date(result.analysedAt).toLocaleDateString()}

Verdict: ${
  result.verdict === 'likely-ai' ? 'Likely AI-generated'
  : result.verdict === 'mixed' ? 'Mixed — AI and human'
  : 'Likely human-written'
}
AI probability: ${result.overallAiPct}%
Confidence: ${result.confidence}
Words analysed: ${result.wordCount}

Top flagged sentences:
${result.sentences
  .filter(s => s.aiProbability >= 40)
  .sort((a, b) => b.aiProbability - a.aiProbability)
  .slice(0, 3)
  .map(s => `• [${s.aiProbability}%] "${s.text}"`)
  .join('\n')}

Generated by Humaniser AI Detector — humaniseai.co.za`.trim()
}

// ── VerdictBadge ──────────────────────────────────────────────────────────────

const VERDICT_CONFIG = {
  'likely-ai': {
    label: 'Likely AI-generated',
    cls: 'bg-red-50 text-red-600 border-red-200',
    Icon: AlertTriangle,
  },
  'mixed': {
    label: 'Mixed — AI and human',
    cls: 'bg-amber-50 text-amber-600 border-amber-200',
    Icon: HelpCircle,
  },
  'likely-human': {
    label: 'Likely human-written',
    cls: 'bg-green-50 text-green-600 border-green-200',
    Icon: CheckCircle,
  },
}

function VerdictBadge({ verdict }: { verdict: VerdictType }) {
  const { label, cls, Icon } = VERDICT_CONFIG[verdict]
  return (
    <div className={`inline-flex items-center gap-2 px-3 py-1.5 rounded-lg border text-sm font-medium ${cls}`}>
      <Icon size={15} />
      {label}
    </div>
  )
}

// ── ScoreBar ──────────────────────────────────────────────────────────────────

function ScoreBar({ aiPct, className = '' }: { aiPct: number; className?: string }) {
  const barColor =
    aiPct >= 70 ? 'bg-red-400'
    : aiPct >= 40 ? 'bg-amber-400'
    : 'bg-green-500'

  return (
    <div className={className}>
      <div className="flex items-baseline justify-between mb-1.5">
        <span className="text-xs text-gray-500">AI probability</span>
        <span className="text-2xl font-medium text-gray-900">{aiPct}%</span>
      </div>
      <div className="w-full h-2 bg-gray-100 rounded-full overflow-hidden">
        <div
          className={`h-full rounded-full transition-all duration-700 ${barColor}`}
          style={{ width: `${aiPct}%` }}
        />
      </div>
    </div>
  )
}

// ── SentenceResultRow ─────────────────────────────────────────────────────────

function SentenceResultRow({
  sentence,
  selected,
  onClick,
  onHumanise,
}: {
  sentence: SentenceResult
  selected: boolean
  onClick: () => void
  onHumanise: (text: string) => void
}) {
  const { aiProbability: pct, text } = sentence

  const pctColor =
    pct >= 70 ? 'text-red-500'
    : pct >= 40 ? 'text-amber-500'
    : 'text-green-600'

  const selectedBg =
    pct >= 70 ? 'bg-red-50 border-red-100'
    : pct >= 40 ? 'bg-amber-50 border-amber-100'
    : 'bg-green-50 border-green-100'

  return (
    <div
      onClick={onClick}
      className={`p-3 rounded-lg border cursor-pointer transition-colors ${
        selected ? selectedBg : 'bg-white border-gray-100 hover:bg-gray-50'
      }`}
    >
      <div className="flex items-start justify-between gap-2">
        <p className="text-xs text-gray-700 leading-relaxed line-clamp-2 flex-1">{text}</p>
        <span className={`text-sm font-medium flex-shrink-0 ${pctColor}`}>{pct}%</span>
      </div>

      {pct >= 40 && (
        <button
          type="button"
          onClick={e => {
            e.stopPropagation()
            onHumanise(text)
          }}
          className="mt-2 flex items-center gap-1 text-[11px] text-blue-500 hover:text-blue-700 hover:underline transition-colors"
        >
          <Sparkles size={11} />
          Humanise this sentence
        </button>
      )}
    </div>
  )
}

// ── SentenceHighlightView ─────────────────────────────────────────────────────

function SentenceHighlightView({
  sentences,
  selectedId,
  onSelect,
}: {
  sentences: SentenceResult[]
  selectedId: string | null
  onSelect: (id: string | null) => void
}) {
  return (
    <div className="flex-1 overflow-y-auto px-4 py-3 text-sm text-gray-800 leading-relaxed">
      {sentences.map(s => {
        const isSelected = s.id === selectedId
        const bg =
          s.aiProbability >= 70 ? 'bg-red-50 hover:bg-red-100'
          : s.aiProbability >= 40 ? 'bg-amber-50 hover:bg-amber-100'
          : 'bg-green-50 hover:bg-green-100'
        const border = isSelected
          ? s.aiProbability >= 70 ? 'border-l-2 border-red-400'
            : s.aiProbability >= 40 ? 'border-l-2 border-amber-400'
            : 'border-l-2 border-green-500'
          : 'border-l-2 border-transparent'
        return (
          <span
            key={s.id}
            onClick={() => onSelect(isSelected ? null : s.id)}
            className={`inline cursor-pointer rounded px-0.5 transition-colors ${bg} ${border}`}
          >
            {s.text}{' '}
          </span>
        )
      })}

      <div className="flex items-center gap-4 mt-6 pt-4 border-t border-gray-100">
        <span className="text-xs text-gray-400">Highlight key:</span>
        <span className="flex items-center gap-1.5 text-xs text-gray-500">
          <span className="w-3 h-3 rounded-sm bg-red-100 inline-block" />Likely AI
        </span>
        <span className="flex items-center gap-1.5 text-xs text-gray-500">
          <span className="w-3 h-3 rounded-sm bg-amber-100 inline-block" />Mixed
        </span>
        <span className="flex items-center gap-1.5 text-xs text-gray-500">
          <span className="w-3 h-3 rounded-sm bg-green-100 inline-block" />Likely human
        </span>
      </div>
    </div>
  )
}

// ── InputPanel ────────────────────────────────────────────────────────────────

const MAX_CHARS = 10_000

function InputPanel({
  text,
  onTextChange,
  detectorState,
  wordCount,
  result,
  selectedId,
  onSelect,
  onAnalyse,
  onReset,
}: {
  text: string
  onTextChange: (t: string) => void
  detectorState: DetectorState
  wordCount: number
  result: DetectorUIResult | null
  selectedId: string | null
  onSelect: (id: string | null) => void
  onAnalyse: () => void
  onReset: () => void
}) {
  const { isDragging, isProcessing, dragHandlers, openFilePicker, fileInputElement } = useDragDrop({
    onText: onTextChange,
    disabled: detectorState === 'analysing',
  })

  const charCount = text.length
  const isOverLimit = charCount > MAX_CHARS

  const footerHint =
    isOverLimit ? `Too long — ${charCount.toLocaleString()} / ${MAX_CHARS.toLocaleString()} characters`
    : wordCount >= 200 ? 'Optimal length for accurate detection'
    : wordCount >= 50 ? `${200 - wordCount} more words for best accuracy`
    : wordCount > 0 ? `${50 - wordCount} more words needed`
    : 'Min. 50 words · 200+ for best accuracy'

  return (
    <div className="flex flex-col h-full bg-white border-r border-gray-100 relative" {...dragHandlers}>
      {fileInputElement}
      <DropOverlay isDragging={isDragging} isProcessing={isProcessing} />

      {/* Header */}
      <div className="flex items-center justify-between px-4 py-2.5 border-b border-gray-100 shrink-0">
        <span className="text-sm font-medium text-gray-700">
          Your text
          {wordCount > 0 && (
            <span className="ml-2 text-xs font-normal text-gray-400">{wordCount} words</span>
          )}
        </span>
        <div className="flex items-center gap-3">
          {!text && (
            <button
              type="button"
              onClick={() => onTextChange(SAMPLE_TEXT)}
              className="text-xs text-blue-500 hover:underline"
            >
              Try sample
            </button>
          )}
          <button
            type="button"
            onClick={openFilePicker}
            disabled={detectorState === 'analysing' || isProcessing}
            className="text-xs text-gray-400 hover:text-gray-600 flex items-center gap-1 disabled:opacity-40"
          >
            <Upload size={12} /> Upload
          </button>
        </div>
      </div>

      {/* Content */}
      <div className="flex-1 min-h-0 flex flex-col">
        {detectorState === 'complete' && result ? (
          <SentenceHighlightView
            sentences={result.sentences}
            selectedId={selectedId}
            onSelect={onSelect}
          />
        ) : (
          <textarea
            className="flex-1 w-full px-4 py-3 text-sm text-gray-800 placeholder-gray-400 bg-white resize-none outline-none leading-relaxed"
            placeholder="Paste the text you want to analyse here. Minimum 50 words, 200+ for accurate detection…"
            value={text}
            onChange={e => onTextChange(e.target.value)}
            disabled={detectorState === 'analysing'}
          />
        )}
      </div>

      {/* Footer */}
      <div className="flex items-center justify-between px-4 py-3 border-t border-gray-100 shrink-0">
        <span className={`text-xs ${isOverLimit ? 'text-red-500' : 'text-gray-400'}`}>{footerHint}</span>
        <div className="flex items-center gap-2">
          {detectorState === 'complete' && (
            <button
              type="button"
              onClick={onReset}
              className="text-xs text-gray-400 hover:text-gray-700 flex items-center gap-1"
            >
              <RefreshCw size={12} /> New analysis
            </button>
          )}
          <button
            type="button"
            onClick={onAnalyse}
            disabled={wordCount < 50 || isOverLimit || detectorState === 'analysing'}
            className={`flex items-center gap-2 px-5 py-2 rounded-lg text-sm font-medium transition-colors ${
              wordCount < 50 || isOverLimit || detectorState === 'analysing'
                ? 'bg-gray-200 text-gray-400 cursor-not-allowed'
                : 'bg-gray-900 text-white hover:bg-gray-800'
            }`}
          >
            {detectorState === 'analysing' ? (
              <><RefreshCw size={14} className="animate-spin" /> Analysing…</>
            ) : (
              'Analyse text'
            )}
          </button>
        </div>
      </div>
    </div>
  )
}

