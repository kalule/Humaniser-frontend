import type { DocumentReview } from '../types/reviewer'

const VERDICT_TEXT: Record<DocumentReview['verdict'], string> = {
  Accept: 'Accept',
  Revise: 'Revise & Resubmit',
  Reject: 'Reject',
}

function formatDate(iso: string) {
  return new Date(iso).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' })
}

/** Plain-text render of a DocumentReview, for the client-side .txt export fallback. */
export function generateReviewReportText(review: DocumentReview): string {
  const lines: string[] = []

  lines.push(`${review.documentTitle}`)
  lines.push(`${review.reviewType} Review — ${formatDate(review.createdAt)}`)
  lines.push('')
  lines.push(`Verdict: ${VERDICT_TEXT[review.verdict]}`)
  lines.push(`Overall score: ${review.overallScore}/100`)
  lines.push(`Confidence: ${review.confidencePercent}%`)

  if (review.standardsApplied.length > 0) {
    lines.push('')
    lines.push(`Standards applied: ${review.standardsApplied.join(', ')}`)
  }

  if (review.overviewNarrative) {
    lines.push('')
    lines.push('── Overview ──')
    lines.push(review.overviewNarrative)
  }

  lines.push('')
  lines.push('── Category scores ──')
  review.categoryScores.forEach(cs => lines.push(`${cs.category}: ${cs.score}%`))

  const categories = [...new Set(review.findings.map(f => f.category))]
  for (const category of categories) {
    const findings = review.findings.filter(f => f.category === category)
    lines.push('')
    lines.push(`── ${category} (${findings.length} comment${findings.length === 1 ? '' : 's'}) ──`)
    findings.forEach((f, i) => {
      lines.push(`${i + 1}. [${f.severity}] ${f.text}`)
      if (f.suggestion) lines.push(`   → ${f.suggestion}`)
      if (f.pageReference) lines.push(`   (${f.pageReference})`)
    })
  }

  lines.push('')
  lines.push('Generated by Humaniser AI Document Reviewer — humaniseai.co.za')

  return lines.join('\n')
}

export function reviewReportFilename(documentTitle: string, extension: 'txt' | 'pdf'): string {
  const slug = documentTitle.trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'review'
  return `${slug}-review.${extension}`
}
